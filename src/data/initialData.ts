// Helper to check if a student belongs to a schedule rombel
export function isStudentInRombel(studentRombel: string, scheduleRombel: string): boolean {
  if (studentRombel === scheduleRombel) return true;
  if (scheduleRombel === 'TI 1 & 5') {
    return studentRombel === 'TI 1A' || studentRombel === 'TI 5';
  }
  if (scheduleRombel === 'MI 1U') {
    return studentRombel === 'MI 1A';
  }
  if (scheduleRombel === 'MI 5') {
    return studentRombel === 'MI 5A';
  }
  return false;
}

